const PILL = '[data-testid="goal-pill"]'
const INPUT = 'input[aria-label="目标条件"]'

export default async function (t) {
  const data = await t.data()
  t.ok('目标条按会话路径显示', await t.waitFor(PILL))
  t.ok('执行中的目标含条件', (await t.text(PILL)).includes('完成目标生命周期验收'))
  const normalFill = (await t.style('[aria-label="编辑目标"]', ['background-color'])).backgroundColor
  await t.hover('[aria-label="编辑目标"]')
  t.ok('编辑按钮悬停沿用 ActionIcon 的填充状态', (await t.style('[aria-label="编辑目标"]', ['background-color'])).backgroundColor !== normalFill)
  await t.mouse(2, 2)
  await t.click('[aria-label="编辑目标"]')
  t.ok('编辑入口保持可见', await t.waitFor(INPUT))
  t.checkNear('保存按钮为 24px', (await t.rect('[aria-label="保存目标"]')).w, 24, 1)
  t.checkNear('取消按钮为 24px', (await t.rect('[aria-label="取消编辑"]')).h, 24, 1)
  await t.click(INPUT)
  await t.key('a', ['control'])
  await t.type('草稿在下一轮仍保留')
  await t.act('round')
  t.ok('轮次推进不丢草稿和焦点', await t.waitUntil(`document.querySelector('${INPUT}')?.value === '草稿在下一轮仍保留' && document.activeElement === document.querySelector('${INPUT}')`))
  await t.act('stalePull')
  await t.act('holdPull')
  await t.click('[aria-label="保存目标"]')
  t.ok('延迟提交时保留编辑态', await t.waitFor(INPUT))
  await t.act('releasePull')
  t.ok('保存前启动的旧补拉不退出编辑', await t.waitFor(INPUT))
  await t.act('releaseEdit', 'failed')
  t.ok('提交失败保留草稿', await t.waitForText('[role="alert"]', '草稿已保留'))
  t.ok('提交失败将焦点还给输入框', await t.js(`document.activeElement === document.querySelector('${INPUT}')`))
  await t.shot('save-failed-dark')
  await t.act('editMode', 'commit')
  await t.click('[aria-label="保存目标"]')
  t.ok('失败后可再提交', await t.waitUntil(`!document.querySelector('${INPUT}')`))
  t.ok('本次 committed 才更新条件', (await t.text(PILL)).includes('草稿在下一轮仍保留'))
  await t.click('[aria-label="编辑目标"]')
  await t.click(INPUT)
  await t.key('a', ['control'])
  await t.type('冲突草稿')
  await t.act('externalEdit', '远端条件')
  t.ok('真实条件冲突保留本地草稿', await t.waitForText('[role="alert"]', '其他操作修改'))
  t.ok('冲突选项使用主题文本按钮', await t.js(`[...document.querySelectorAll('${PILL} button')].filter((button) => button.classList.contains('ant-btn-text')).length === 2`))
  await t.shot('conflict-dark')
  await t.click(`${PILL} button.ant-btn:nth-of-type(2)`)
  t.ok('明确基于最新版本后仍保留草稿', await t.waitUntil(`document.querySelector('${INPUT}')?.value === '冲突草稿'`))
  await t.click('[aria-label="保存目标"]')
  t.ok('基于最新版提交仍要实际回执', await t.waitUntil(`!document.querySelector('${INPUT}')`))
  await t.act('freshPull')
  await t.act('failure')
  t.ok('异常暂停原因可见', await t.waitForText('[data-testid="goal-reason"]', '请求重试已耗尽'))
  const frozen = await t.text(PILL)
  await new Promise((resolve) => setTimeout(resolve, 1050))
  t.ok('暂停计时冻结', (await t.text(PILL)).includes(frozen.match(/· [0-9]+[smh]/)?.[0] ?? '· 2m'))
  await t.act('exhausted')
  t.ok('轮次耗尽入口写明新批次', await t.waitFor('[aria-label="开启新批次"]'))
  await t.click('[aria-label="展开目标详情"]')
  t.ok('详情区分本批次与累计', await t.waitForText('.ant-drawer-body', '第 1 批 · 已用 2 / 2 轮'))
  t.ok('详情也显示重启按钮', await t.waitForText('.ant-drawer-body', '开启新批次（保留累计历史）'))
  await t.shot('exhausted-dark')
  await t.click('.ant-drawer-close')
  await t.click('[aria-label="开启新批次"]')
  t.ok('新批次回复后仍保留累计', await t.waitForText(PILL, '执行中的目标'))
  await t.click('[aria-label="展开目标详情"]')
  t.ok('新批次数量归零', await t.waitForText('.ant-drawer-body', '第 2 批 · 已用 0 / 2 轮'))
  t.ok('旧批次累计不清零', await t.waitForText('.ant-drawer-body', '2 轮'))
  await t.click('.ant-drawer-close')
  await t.setTheme('light')
  await t.click('[aria-label="编辑目标"]')
  t.check('未改动时保存按钮不可聚焦', await t.js('document.querySelector(\'[aria-label="保存目标"]\').tabIndex'), -1)
  await t.click(INPUT)
  t.ok('浅色输入获取键盘焦点', await t.js(`document.activeElement === document.querySelector('${INPUT}')`))
  await t.shot('edit-light')
  await t.key('Escape')
  t.check('Esc 取消编辑', await t.count(INPUT), 0)
  await t.act('unavailable')
  t.ok('写盘失败不伪装为已暂停', await t.waitForText(PILL, '目标已停止 · 暂停未保存'))
  t.ok('写盘失败提供重新读取', await t.waitFor('[aria-label="重新读取目标状态"]'))
  await t.click('[aria-label="重新读取目标状态"]')
  t.ok('按原路径发起只读补拉', (await t.events()).some((event) => event === `pull:${data.path}`))
  await t.shot('unavailable-light')
  await t.resize(380, 740)
  t.ok('窄栏不横向溢出', await t.js('document.documentElement.scrollWidth <= window.innerWidth + 2'))
  await t.shot('narrow-light')
}
