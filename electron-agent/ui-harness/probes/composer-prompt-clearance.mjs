const overlay = '[data-testid="composer-prompt-overlay"]'
const scroller = '[data-testid="chat-scroll"] > div'
async function visibleTail(t, label, obstruction = overlay) {
  await t.sleep(350)
  const tail = await t.rect('[data-testid="clearance-row-29"]')
  const card = await t.rect(obstruction)
  t.ok(label, tail.y + tail.h <= card.y + 1)
}
export default async function (t) {
  await t.waitFor(scroller)
  await visibleTail(t, '初始输入区不遮正文', '[data-testid="clearance-seat"]')
  await t.act('select')
  await t.waitFor(overlay)
  await visibleTail(t, '选项卡弹出后结尾可见')
  await t.act('question')
  await visibleTail(t, '询问卡弹出后结尾可见')
  await t.act('question', true)
  await visibleTail(t, '换成长题后重新避让')
  await t.act('seat', 160)
  await visibleTail(t, '输入区变高导致浮层移动后重新避让')
  await t.resize(760, 720)
  await visibleTail(t, '窗口缩小后重新避让')
  const r = await t.rect(scroller)
  await t.wheel({ x: Math.round(r.x + r.w / 2), y: Math.round(r.y + 40) }, -500)
  await t.sleep(350)
  const before = await t.js(`document.querySelector('${scroller}').scrollTop`)
  await t.act('question', false)
  await t.sleep(350)
  const after = await t.js(`document.querySelector('${scroller}').scrollTop`)
  t.ok('用户上翻后换题不强制贴底', Math.abs(after - before) < 3)
  const jump = '[data-testid="jump-to-bottom"]'
  await t.waitFor(jump)
  const button = await t.rect(jump)
  const card = await t.rect(overlay)
  t.ok('回到底部按钮在卡片上方', button.y + button.h <= card.y)
  await t.click(jump)
  await visibleTail(t, '手动回到底部后结尾可见')
  await t.act('close')
  await visibleTail(t, '关闭恢复输入区留白', '[data-testid="clearance-seat"]')
  await t.act('select')
  await t.act('session')
  await visibleTail(t, '切会话不残留浮层留白', '[data-testid="clearance-seat"]')
  t.ok('切会话恢复准确留白', await t.js(`document.querySelector('[data-testid="seat-spacer"]').offsetHeight === 160`))
}
