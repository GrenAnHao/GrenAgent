const DOCK = '[data-testid="todo-dock"]'
async function completed(t, label) {
  t.ok(label, await t.waitForText(DOCK, '3 已完成'))
  t.ok(`${label}：没有残留进行中`, !(await t.text(DOCK)).includes('进行中'))
}
export default async function (t) {
  t.ok('起点：与截图一致的两完成、一进行中', await t.waitForText(DOCK, '2 已完成'))
  t.ok('起点：进行中任务仍在执行', (await t.text(DOCK)).includes('1 进行中'))
  await t.act('missingStart')
  await completed(t, '缺失 start：最终成功结果立即显示')
  await t.click(`${DOCK} button[aria-label="任务"]`)
  t.check('展开：保留三个任务行', await t.count('[data-testid="todo-dock-list"] li'), 3)
  await t.act('lateProgress')
  await completed(t, '迟到进度：不会把终态退回待办')
  await t.act('failedWrite')
  await completed(t, '失败写入：保留上一成功清单')
  await t.act('clear')
  t.ok('显式清空：任务条立即消失', await t.waitUntil(`document.querySelectorAll('${DOCK}').length === 0`))
  await t.act('completeFromMessage')
  await completed(t, '仅 toolResult：成功清单恢复')
  await t.act('roundRecovery')
  await completed(t, '回合完整结果：补回缺失最终写入')
  await t.act('longHistory')
  await completed(t, '较长 UI 历史：以后端 todo 结果校准')
  await t.act('sameLengthAbort')
  t.ok('中断：不把进行中伪装成完成', await t.waitForText(DOCK, '1 进行中'))
  t.check('中断：派生标记为未完成', (await t.data()).finished, false)
  await t.act('cached')
  await completed(t, '切回缓存：正常收尾状态立即恢复')
  await t.act('wakeCached')
  await completed(t, '后台通知唤起：已经收尾的任务不重新变为进行中')
  await t.act('rapid')
  await completed(t, '同帧连续更新：新清单不被旧调用的迟到结果覆盖')
  await t.act('outOfOrder')
  await completed(t, '缺失开始帧加乱序：完整结果恢复源顺序')
  t.check('乱序恢复：成功快照本身已完成，不靠显示层补成完成', (await t.data()).statuses, ['completed', 'completed', 'completed'])
  await t.act('settledWithoutEnd')
  await completed(t, '缺失 agent_end：最终 settled 仍能从消息恢复收尾')
  t.check('最终 settled：运行态已结束', (await t.data()).runActive, false)
  await t.setTheme('light')
  await completed(t, '浅色：状态与深色一致')
  await t.click(`${DOCK} button[aria-label="任务"]`)
  t.check('最终展开：三个任务仍完整', await t.count('[data-testid="todo-dock-list"] li'), 3)
  t.check('最终展开：没有仍在执行的任务行', await t.count('[data-testid="todo-dock-list"] [data-busy="true"]'), 0)
  await t.shot('todo-completed-light')
  await t.act('nextUser')
  t.ok('下一轮：已完成任务条收起', await t.waitUntil(`document.querySelectorAll('${DOCK}').length === 0`))
}
