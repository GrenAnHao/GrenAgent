const snapshot = (t) => t.act('snapshot');
const clickMarkdownLink = async (t, label, key) => {
  await t.js(`Array.from(document.querySelectorAll('.markdown button.inline-page')).find(button => button.textContent.trim() === ${JSON.stringify(label)})?.setAttribute('data-ui-link', ${JSON.stringify(key)})`);
  await t.click(`[data-ui-link="${key}"]`);
};

