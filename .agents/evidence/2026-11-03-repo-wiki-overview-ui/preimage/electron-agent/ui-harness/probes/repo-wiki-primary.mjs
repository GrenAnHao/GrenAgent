export default async function (t) {
  await t.waitFor('[aria-label="Repo Wiki 概览"]');
  let calls = await t.act('calls');
  t.check('读取和挂载不保存或启动', calls.filter(x => x.command === 'repoWiki_native' && ['author.save', 'prepare', 'start'].includes(x.args.command)).length, 0);
  t.check('没有第二个原版入口', await t.count('[aria-label="原版 Wiki 生成"]'), 0);
  await t.click('[aria-label="生成语言"]'); await t.key('End'); await t.key('Enter');
  await t.waitUntil(`document.querySelector('[aria-label="生成语言"]')?.value === 'en'`);
  await t.click('[aria-label="生成语言"]'); await t.key('Home'); await t.key('Enter');
  await t.waitUntil(`document.querySelector('[aria-label="生成语言"]')?.value === 'zh'`);
  calls = await t.act('calls');
  t.check('切换语言不保存或启动', calls.filter(x => x.command === 'repoWiki_native' && ['author.save', 'prepare', 'start'].includes(x.args.command)).length, 0);
  await t.waitFor('[data-native-intent="full"]:not([disabled])');
  await t.click('[data-native-intent="full"]');
  await t.waitFor('[aria-label="确认外发模型"]');
  calls = await t.act('calls');
  t.check('默认作者先保存再准备', calls.filter(x => x.command === 'repoWiki_native' && ['author.save', 'prepare'].includes(x.args.command)).map(x => x.args.command).join(','), 'author.save,prepare');
  t.check('确认之前不启动', calls.filter(x => x.command === 'repoWiki_native' && x.args.command === 'start').length, 0);
  await t.click('[aria-label="确认外发并开始"]');
  calls = await t.act('calls');
  t.check('宿主收到服务端 task_id', (await t.act('taskIds')).join(','), 'native:fixture-native');
  t.check('确认后启动 native', calls.filter(x => x.command === 'repoWiki_native' && x.args.command === 'start').length, 1);
  t.check('没有旧生成或动作', calls.filter(x => ['repoWiki_generate', 'repoWiki_action'].includes(x.command)).length, 0);
  await t.waitFor('[aria-label="取消原生运行"]:not([disabled])');
  await t.click('[aria-label="取消原生运行"]');
  await t.waitFor('[data-native-intent="update"]:not([disabled])');
  await t.click('[data-native-intent="update"]');
  await t.waitFor('[aria-label="确认外发模型"]');
  await t.click('[aria-label="确认外发并开始"]');
  await t.waitFor('[aria-label="取消原生运行"]:not([disabled])');
  calls = await t.act('calls');
  t.check('新任务启动后刷新最新状态而不锁定 A', calls.filter(x => x.command === 'repoWiki_native' && x.args.command === 'status').at(-1).args.operation_id, undefined);
  t.check('每次启动消费服务端 task_id', (await t.act('taskIds')).join(','), 'native:fixture-native,native:fixture-native-2');
  await t.click('[aria-label="取消原生运行"]');
  t.check('控制操作绑定 B', (await t.act('calls')).filter(x => x.command === 'repoWiki_native' && x.args.command === 'control').at(-1).args.operation_id, 'fixture-native-2');
  await t.waitFor('[aria-label="刷新原生状态"]:not([disabled])');
  await t.act('externalNative');
  await t.click('[aria-label="刷新原生状态"]');
  t.ok('刷新发现外部新任务', await t.waitForText('[aria-label="原版生成状态"]', '外部新任务'));
  t.check('主概览刷新不锁定旧任务', (await t.act('calls')).filter(x => x.command === 'repoWiki_native' && x.args.command === 'status').at(-1).args.operation_id, undefined);
  await t.waitFor('[aria-label="刷新原生状态"]:not([disabled])');
  await t.act('publishNative');
  await t.click('[aria-label="刷新原生状态"]');
  t.ok('发布后刷新左侧目录', await t.waitForText('.wiki-tree', '原生新页面'));
  await t.js(`Array.from(document.querySelectorAll('.wiki-tree [role="treeitem"]')).find(item => item.textContent.includes('原生新页面'))?.setAttribute('data-new-page', 'true')`);
  await t.click('[data-new-page]');
  t.ok('发布页可以阅读', await t.waitForText('.markdown', '原生发布正文'));
  await t.click('.knowledge-overview-link');
  await t.act('nativeRunning');
  await t.click('[aria-label="刷新原生状态"]');
  await t.waitFor('[aria-label="暂停原版运行"]:not([disabled])');
  await t.click('[data-new-page]');
  await t.waitForText('.markdown', '原生发布正文');
  await t.act('holdProjectRead');
  await t.act('publishSecond');
  await t.act('projectReadStarted');
  await t.click('.knowledge-overview-link');
  await t.act('releaseProjectRead');
  t.ok('同项目页面切换不丢在途发布目录更新', await t.waitForText('.wiki-tree', '后续发布页面'));
  await t.click('[aria-label="查看旧引擎历史草稿"]');
  t.ok('旧任务标明引擎和 ID', (await t.text('[role="dialog"]')).includes('旧引擎 · 任务 ID：legacy-budget'));
  t.check('九份旧草稿均可访问', await t.count('[aria-label="未发布草稿目录"] button'), 9);
  t.ok('旧草稿可读', (await t.text('[role="dialog"]')).includes('架构草稿'));
  await t.js(`Array.from(document.querySelectorAll('[aria-label="未发布草稿正文"] .inline-page')).find(button => button.textContent.trim() === '同层草稿')?.setAttribute('data-old-sibling', 'true')`);
  await t.click('[data-old-sibling]');
  t.ok('旧草稿内链接只读跳转', await t.waitForText('[aria-label="未发布草稿正文"]', '同层草稿已打开。'));

  await t.key('Escape');
  await t.act('clearLegacy');
  await t.click('[aria-label="知识卡片"]');
  await t.waitFor('[data-knowledge-action="generate"]');
  await t.click('[data-knowledge-action="generate"]');
  await t.waitFor('[role="dialog"][aria-label="允许发送源码到模型服务？"]');
  await t.click('[role="dialog"] .modal-actions .primary');
  calls = await t.act('calls');
  t.check('知识卡片仍调用旧卡片生成', calls.filter(x => x.command === 'repoWiki_generate' && x.args.target === 'cards').length, 1);
  await t.click('[aria-label="Wiki 文档"]');
  await t.act('changeWorkspace'); await t.waitFor('[aria-label="Repo Wiki 概览"]');
  await t.act('returnWorkspace'); await t.waitFor('[aria-label="Repo Wiki 概览"]');
  calls = await t.act('calls');
  t.check('切换项目不启动新任务', calls.filter(x => x.command === 'repoWiki_native' && x.args.command === 'start').length, 2);
}
